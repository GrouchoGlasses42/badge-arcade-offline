"""Verified address tables for the supplied EUR executable revisions."""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Revision:
    version: str
    sha256: str
    size: int
    input_name: str
    addresses: dict[int, int] = field(default_factory=dict)
    world_shift: int = 0

    def address(self, value: int) -> int:
        return self.addresses.get(value, value)


